def translate_processor(request):
    lang = getattr(request, 'LANGUAGE_CODE', 'uz')
    context = {'T': TRANSLATIONS.get(lang, TRANSLATIONS['uz'])}
    if request.user.is_authenticated:
        context['unread_notifications_count'] = Notification.objects.filter(user=request.user, is_read=False).count()
    return context
